"use client";

/**
 * AuditPdfHistory — Phase 4 Wave 2 PR C4.
 *
 * "Generated audit PDFs" history table on the Customer detail page.
 * Backed by ``GET /v1/customers/{customer_id}/audit-pdfs`` (paginated,
 * newest first) and ``POST .../regenerate`` (re-render on click).
 *
 * Storage decision (v1): the backend does NOT persist rendered PDF
 * bytes — re-download regenerates from the persisted ``(date_from,
 * date_to, sections, branding)`` tuple. That means each Re-download
 * incurs the same 5-30s render budget as the original Generate.
 *
 * Single surface — no Compliance roll-up by v1 design decision.
 * The Generate button itself lives in the Customer detail header
 * (C3-scaffold) so this section has NO CTA in its empty state.
 *
 * States
 * ======
 * - loading  → skeleton rows (six rows × column widths)
 * - error    → inline error banner with retry hint
 * - empty    → flat copy line, no CTA
 * - loaded   → table + "Load more" button when total > items.length
 *
 * Columns
 * =======
 *   Generated  |  Generated by  |  Date range  |  Sections  |  Branding
 *              |  Size          |  (re-download)
 *
 * Per CLAUDE.md voice rules:
 *   - "Customer" (not "Tenant") in copy
 *   - Full date with year ("Mar 15, 2026" — never "Mar 15")
 *   - Comma-separated bytes ("12,500")
 *   - tabular-nums on every rendered number
 *   - "Consider…" / "Recommended:" only (no bare imperatives) — N/A here
 */

import * as React from "react";

import { Loading } from "@/components/ui/loading";
import { Skeleton } from "@/components/ui/skeleton";
import {
  ApiError,
  AUDIT_PDF_SECTION_KEYS,
  type AuditPdfHistoryItem,
  type GeneratedBy,
  readAuditPdfErrorCode,
  regenerateAuditPdf,
} from "@/lib/api-client";
import { useAuditPdfHistory } from "@/hooks/use-customers";

const PAGE_SIZE = 20;
const TOTAL_SECTION_COUNT = AUDIT_PDF_SECTION_KEYS.length; // 8

interface AuditPdfHistoryProps {
  /** Customer **primary key** (UUID). Not the tenant_id slug. */
  customer_id: string;
}

export function AuditPdfHistory({ customer_id }: AuditPdfHistoryProps) {
  const [pageCount, setPageCount] = React.useState(1);
  const limit = pageCount * PAGE_SIZE;

  const { data, isLoading, isError, error } = useAuditPdfHistory(
    customer_id,
    { limit, offset: 0 },
    !!customer_id,
  );

  // Per-row regenerate state. We track the in-flight pdf id and any
  // last-error code per row so the inline banner can render alongside
  // the table without disrupting other rows.
  const [regeneratingId, setRegeneratingId] = React.useState<string | null>(
    null,
  );
  const [rowErrorById, setRowErrorById] = React.useState<
    Record<string, string | null>
  >({});

  const onRegenerate = React.useCallback(
    async (item: AuditPdfHistoryItem) => {
      if (regeneratingId) return;
      setRegeneratingId(item.id);
      setRowErrorById((prev) => ({ ...prev, [item.id]: null }));
      try {
        await regenerateAuditPdf(customer_id, item.id);
      } catch (e) {
        const code = readAuditPdfErrorCode(e);
        const message = mapRegenerateErrorMessage(code, e);
        setRowErrorById((prev) => ({ ...prev, [item.id]: message }));
      } finally {
        setRegeneratingId(null);
      }
    },
    [customer_id, regeneratingId],
  );

  return (
    <section
      className="space-y-3"
      data-testid="audit-pdf-history"
      aria-labelledby="audit-pdf-history-heading"
    >
      <h2
        id="audit-pdf-history-heading"
        className="text-[11px] font-semibold uppercase tracking-[0.08em] text-[color:var(--ink-2)]"
      >
        Audit PDFs
      </h2>

      {isLoading ? (
        <AuditPdfHistorySkeleton />
      ) : isError ? (
        <ErrorBanner message={error?.message ?? null} />
      ) : !data || data.items.length === 0 ? (
        <EmptyRow />
      ) : (
        <HistoryTable
          items={data.items}
          total={data.total}
          onRegenerate={onRegenerate}
          regeneratingId={regeneratingId}
          rowErrorById={rowErrorById}
          onLoadMore={
            data.items.length < data.total
              ? () => setPageCount((c) => c + 1)
              : null
          }
        />
      )}
    </section>
  );
}

