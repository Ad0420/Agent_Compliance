function AuditPdfHistorySkeleton() {
  return (
    <div
      className="space-y-2 rounded-md border border-[color:var(--ink-4)] bg-[color:var(--paper)] p-3"
      aria-busy="true"
      data-testid="audit-pdf-history-loading"
    >
      {Array.from({ length: 4 }).map((_, i) => (
        <div key={i} className="flex items-center gap-4">
          <Skeleton className="h-4 w-32" />
          <Skeleton className="h-4 w-28" />
          <Skeleton className="h-4 w-40" />
          <Skeleton className="h-4 w-20" />
          <Skeleton className="h-4 w-24" />
          <Skeleton className="h-4 w-16" />
        </div>
      ))}
    </div>
  );
}

function ErrorBanner({ message }: { message: string | null }) {
  return (
    <div
      role="alert"
      className="rounded-md border border-[color:var(--brick)]/30 bg-[color:var(--brick-bg)] px-4 py-3 text-[13px] text-[color:var(--ink)]"
      data-testid="audit-pdf-history-error"
    >
      <p className="font-medium">Audit PDF history could not be loaded.</p>
      <p className="mt-1 text-[12px] text-[color:var(--ink-2)]">
        {message ??
          "Refresh the page. If the problem persists, contact support."}
      </p>
    </div>
  );
}

function EmptyRow() {
  return (
    <p
      className="rounded-md border border-dashed border-[color:var(--ink-4)] bg-[color:var(--paper-2)] px-4 py-6 text-[13px] text-[color:var(--ink-2)]"
      data-testid="audit-pdf-history-empty"
    >
      No audit PDFs generated yet for this Customer.
    </p>
  );
}

